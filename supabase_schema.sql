create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  title text not null check (char_length(title) between 1 and 300),
  due_date date not null default current_date,
  priority text not null default 'Medium' check (priority in ('High','Medium','Low')),
  category text not null default 'Other',
  done boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  description text not null check (char_length(description) between 1 and 300),
  category text not null default 'Other',
  amount numeric(12,2) not null check (amount > 0),
  expense_date date not null default current_date,
  created_at timestamptz not null default now()
);

alter table public.tasks enable row level security;
alter table public.expenses enable row level security;

drop policy if exists "Users manage their own tasks" on public.tasks;
create policy "Users manage their own tasks" on public.tasks
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users manage their own expenses" on public.expenses;
create policy "Users manage their own expenses" on public.expenses
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

create index if not exists tasks_user_created_idx on public.tasks(user_id, created_at desc);
create index if not exists expenses_user_date_idx on public.expenses(user_id, expense_date desc);

-- Anonymous product feedback for usability testing. Do not collect names or emails.
create table if not exists public.product_feedback (
  id bigint generated by default as identity primary key,
  overall_rating smallint not null check (overall_rating between 1 and 5),
  answer_quality smallint not null check (answer_quality between 1 and 5),
  response_speed smallint not null check (response_speed between 1 and 5),
  ease_of_use smallint not null check (ease_of_use between 1 and 5),
  feature_tested text not null check (char_length(feature_tested) between 1 and 80),
  would_recommend text not null check (would_recommend in ('Yes','Maybe','No')),
  comments text not null default '' check (char_length(comments) <= 1000),
  created_at timestamptz not null default now()
);

alter table public.product_feedback enable row level security;
drop policy if exists "Anyone can submit anonymous product feedback" on public.product_feedback;
create policy "Anyone can submit anonymous product feedback" on public.product_feedback
  for insert to anon, authenticated with check (true);

